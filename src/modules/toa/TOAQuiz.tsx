export default function TOAQuiz({ moduleId }: { moduleId: TOAModuleId }) {
  const mod = getTOAModule(moduleId)
  const questions = TOA_QUIZ_QUESTIONS[moduleId] || TOA_QUIZ_QUESTIONS['toa-m1']

  const [selectedAnswers, setSelectedAnswers] = useState<Record<string, number>>({})
  const [submitted, setSubmitted] = useState(false)

  const handleSelect = (qId: string, idx: number) => {
    if (submitted) return
    setSelectedAnswers(prev => ({ ...prev, [qId]: idx }))
  }

  const score = useMemo(() => {
    let correct = 0
    questions.forEach(q => {
      if (selectedAnswers[q.id] === q.answerIndex) correct++
    })
    return correct
  }, [questions, selectedAnswers])

  const handleReset = () => {
    setSelectedAnswers({})
    setSubmitted(false)
  }

  if (!mod) return null

  return (
    <div className="space-y-8 max-w-4xl mx-auto">
      {/* Quiz Header Banner */}
      <Card className="border border-ink shadow-[4px_4px_0_var(--rule)] bg-card">
        <CardHeader className="border-b border-rule pb-4">
          <div className="flex items-center justify-between font-mono text-xs mb-1">
            <span className="px-2 py-0.5 bg-signal text-paper font-bold uppercase">Theory of Automata Practice Test</span>
            <span className="text-ink-soft">{questions.length} Questions · University Syllabus</span>
          </div>
          <CardTitle className="font-serif text-2xl font-bold text-ink">
            {mod.code}: {mod.title}
          </CardTitle>
          <p className="font-sans text-xs text-ink-soft mt-1">
            Test your understanding of state machines, theorems, grammar derivations, and automata complexities.
          </p>
        </CardHeader>
      </Card>

      {/* Question Cards */}
      <div className="space-y-6">
        {questions.map((q, qIndex) => {
          const userAnswer = selectedAnswers[q.id]
          const isCorrect = userAnswer === q.answerIndex

          return (
            <Card
              key={q.id}
              className={`border-2 transition-all ${
                submitted
                  ? isCorrect
                    ? "border-ok bg-ok/5"
                    : "border-bad bg-bad/5"
                  : "border-ink bg-card shadow-[3px_3px_0_var(--rule)]"
              }`}
            >
              <CardHeader className="border-b border-rule/60 pb-3">
                <div className="flex items-start justify-between gap-2">
                  <div className="space-y-1">
                    <span className="font-mono text-xs font-bold text-signal">
                      Question {qIndex + 1} of {questions.length}
                    </span>
                    <h4 className="font-serif text-base font-bold text-ink leading-snug">
                      {q.prompt}
                    </h4>
                  </div>
                  {submitted && (
                    <div>
                      {isCorrect ? (
                        <CheckCircle2 className="h-6 w-6 text-ok shrink-0" />
                      ) : (
                        <XCircle className="h-6 w-6 text-bad shrink-0" />
                      )}
                    </div>
                  )}
                </div>

                {q.scenario && (
                  <p className="font-mono text-[11px] text-ink-soft italic pt-1">
                    Scenario: {q.scenario}
                  </p>
                )}
              </CardHeader>

              <CardContent className="p-4 space-y-2">
                <div className="space-y-2">
                  {q.options.map((opt, optIdx) => {
                    const isSelected = userAnswer === optIdx
                    const isAnswerOption = q.answerIndex === optIdx

                    let btnStyle = "border-rule bg-paper text-ink hover:border-ink"
                    if (submitted) {
                      if (isAnswerOption) {
                        btnStyle = "border-ok bg-ok/20 text-ink font-bold"
                      } else if (isSelected && !isCorrect) {
                        btnStyle = "border-bad bg-bad/20 text-bad font-semibold"
                      } else {
                        btnStyle = "border-rule/40 bg-paper/50 text-ink-soft opacity-60"
                      }
                    } else if (isSelected) {
                      btnStyle = "border-signal bg-signal text-paper font-bold shadow-xs"
                    }

                    return (
                      <button
                        key={optIdx}
                        onClick={() => handleSelect(q.id, optIdx)}
                        disabled={submitted}
                        className={`w-full text-left p-3 border font-sans text-xs transition-colors flex items-center justify-between ${btnStyle} cursor-pointer`}
                      >
                        <div className="flex items-center gap-2.5">
                          <span className="font-mono text-[11px] font-bold opacity-75">
                            {String.fromCharCode(65 + optIdx)}.
                          </span>
                          <span>{opt}</span>
                        </div>
                        {submitted && isAnswerOption && (
                          <span className="font-mono text-[10px] text-ok font-bold uppercase">Correct Answer</span>
                        )}
                      </button>
                    )
                  })}
                </div>

                {/* Explanation */}
                {submitted && (
                  <div className="mt-3 p-3 bg-paper border border-rule font-sans text-xs space-y-1">
                    <div className="font-mono text-[10px] uppercase font-bold text-signal flex items-center gap-1">
                      <Lightbulb className="h-3.5 w-3.5" />
                      <span>Academic Solution &amp; Examiner Note</span>
                    </div>
                    <p className="text-ink leading-relaxed">
                      {q.explanation}
                    </p>
                  </div>
                )}
              </CardContent>
            </Card>
          )
        })}
      </div>

      {/* Submission Controls & Score Summary */}
      <div className="p-6 border-2 border-ink bg-card shadow-[4px_4px_0_var(--rule)] flex flex-col sm:flex-row items-center justify-between gap-4 font-mono">
        <div>
          {!submitted ? (
            <div className="text-xs text-ink-soft">
              Answered <strong className="text-ink">{Object.keys(selectedAnswers).length}</strong> of{" "}
              <strong>{questions.length}</strong> questions
            </div>
          ) : (
            <div className="space-y-1">
              <div className="text-base font-bold text-ink flex items-center gap-2">
                <Award className="h-5 w-5 text-signal" />
                <span>Test Score: {score} / {questions.length} ({Math.round((score / questions.length) * 100)}%)</span>
              </div>
              <p className="text-[11px] text-ink-soft">
                {score === questions.length
                  ? "Outstanding! Perfect score on Automata Theory concepts."
                  : score >= Math.ceil(questions.length / 2)
                  ? "Passed! Review the solutions above to polish university proofs."
                  : "Needs revision. Review the cheat sheet and re-attempt the quiz."}
              </p>
            </div>
          )}
        </div>

        <div className="flex items-center gap-3">
          {!submitted ? (
            <Button
              onClick={() => setSubmitted(true)}
              disabled={Object.keys(selectedAnswers).length === 0}
              className="px-6 py-2.5 bg-signal text-paper font-bold hover:bg-signal/90 font-mono text-xs uppercase"
            >
              Submit Answers →
            </Button>
          ) : (
            <Button
              onClick={handleReset}
              variant="outline"
              className="px-5 py-2.5 border-ink text-ink font-bold font-mono text-xs uppercase flex items-center gap-1.5"
            >
              <RotateCcw className="h-3.5 w-3.5" />
              <span>Retry Test</span>
            </Button>
          )}
        </div>
      </div>
    </div>
  )
}
